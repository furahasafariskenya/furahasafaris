<p data-it="Partenza direttamente dai vostri alloggi alle ore 9.30. Si attraversa Malindi e si prosegue in direzione Che Shale, anche conosciuta come &quot;Sabbia Dorata&quot; per il suo bagnasciuga che assume il colore dell&#x27;oro, dove si può effettuare una prima sosta alla scoperta di una delle spiagge più belle della costa. Si prosegue poi per Ngomeni, dove c&#x27;è la fabbrica del sale, una grande distesa di saline ricche di gamberetti e di fenicotteri rosa, che si può ammirare lungo il tragitto." data-en="Departure directly from your accommodation at 9.30am. You pass through Malindi and continue towards Che Shale, also known as &quot;Golden Sand&quot; for its shoreline that takes on the colour of gold, where you can make a first stop to discover one of the most beautiful beaches on the coast. You then continue to Ngomeni, where the salt factory is located — a vast stretch of salt flats rich in shrimps and pink flamingos, which you can admire along the way." data-fr="Départ directement de votre hébergement à 9 h 30. Vous traversez Malindi en direction de Che Shale, également appelée « Sable doré » en raison de son rivage aux reflets d’or. Vous pourrez y faire un premier arrêt pour découvrir l’une des plus belles plages de la côte. Vous continuerez ensuite vers Ngomeni, où se trouve l’usine de sel et une vaste étendue de marais salants riches en crevettes et en flamants roses." data-de="Direkt von Ihrer Unterkunft geht es um 9:30 Uhr los. Sie fahren durch Malindi weiter nach Che Shale, wegen seines goldschimmernden Strandes auch „Goldener Sand“ genannt. Dort legen Sie einen ersten Stopp an einem der schönsten Strände der Küste ein. Anschließend geht es weiter nach Ngomeni zur Saline – einer weiten Landschaft mit Garnelen und rosa Flamingos.">Partenza direttamente dai vostri alloggi alle ore 9.30. Si attraversa Malindi e si prosegue in direzione Che Shale, anche conosciuta come "Sabbia Dorata" per il suo bagnasciuga che assume il colore dell'oro, dove si può effettuare una prima sosta alla scoperta di una delle spiagge più belle della costa. Si prosegue poi per Ngomeni, dove c'è la fabbrica del sale, una grande distesa di saline ricche di gamberetti e di fenicotteri rosa, che si può ammirare lungo il tragitto.</p>
      <p data-it="Procediamo in direzione dell'isola di Robinson, attraversando una strada sterrata che costeggia il lago salato di Gongini, un luogo frequentato da molte specie di uccelli tra cui aironi, garzette e fenicotteri." data-en="We continue towards Robinson Island, crossing a dirt road that skirts the salt lake of Gongini, a place frequented by many bird species including herons, egrets and flamingos.">Procediamo in direzione dell'isola di Robinson, attraversando una strada sterrata che costeggia il lago salato di Gongini, un luogo frequentato da molte specie di uccelli tra cui aironi, garzette e fenicotteri.</p>
<p data-it="Lasciamo la macchina nelle vicinanze di una laguna, dove si trova un certo &quot;Caronte&quot; che, con la sua canoa, traghetta i turisti nel fantastico paesaggio dell&#x27;isola. A volte, per via della bassa marea, l&#x27;isola può essere raggiunta a piedi attraverso la laguna delle mangrovie." data-en="We leave the car near a lagoon, where a certain &quot;Charon&quot; with his canoe ferries tourists into the fantastic landscape of the island. Sometimes, due to low tide, the island can be reached on foot through the mangrove lagoon." data-fr="Nous laissons la voiture près d’une lagune, où un certain « Charon » transporte les visiteurs en canoë dans le paysage extraordinaire de l’île. À marée basse, il est parfois possible de rejoindre l’île à pied en traversant la lagune de mangrove." data-de="Wir stellen das Auto in der Nähe einer Lagune ab. Dort bringt ein gewisser „Charon“ die Besucher mit seinem Kanu in die fantastische Inselwelt. Bei Ebbe kann die Insel manchmal zu Fuß durch die Mangrovenlagune erreicht werden.">Lasciamo la macchina nelle vicinanze di una laguna, dove si trova un certo "Caronte" che, con la sua canoa, traghetta i turisti nel fantastico paesaggio dell'isola. A volte, per via della bassa marea, l'isola può essere raggiunta a piedi attraverso la laguna delle mangrovie.</p>
      <p data-it="Giunti sull'isola, in attesa del pranzo, è possibile rilassarsi in spiaggia oppure fare una passeggiata verso il villaggio dei pescatori." data-en="On arrival at the island, while waiting for lunch, you can relax on the beach or take a walk to the fishermen's village.">Giunti sull'isola, in attesa del pranzo, è possibile rilassarsi in spiaggia oppure fare una passeggiata verso il villaggio dei pescatori.</p>
      <p data-it="Si pranza al Coco Beach, un suggestivo ristorante tipico africano, costruito con tetto in makuti. Il menù è a base di riso con sugo di polipo, granchi rossi giganti tipici dell'isola di Robinson, vongole e ostriche locali gratinate al cocco, pesce alla griglia, frutta tropicale e tipico caffè Arabo." data-en="Lunch is served at Coco Beach, a charming typical African restaurant built with a makuti thatched roof. The menu features rice with octopus sauce, giant red crabs typical of Robinson Island, local cockles and oysters gratinated with coconut, grilled fish, tropical fruit and typical Arabic coffee.">Si pranza al Coco Beach, un suggestivo ristorante tipico africano, costruito con tetto in makuti. Il menù è a base di riso con sugo di polipo, granchi rossi giganti tipici dell'isola di Robinson, vongole e ostriche locali gratinate al cocco, pesce alla griglia, frutta tropicale e tipico caffè Arabo.</p>
